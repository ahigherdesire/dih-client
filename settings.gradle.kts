// Minecraft 1.21.11 is obfuscated, so its node needs Loom's remapping plugin instead of the no-remap one. Its
// buildscript is build.fabric.gradle.kts with only that plugin swapped, regenerated here so the two never drift.
run {
    val fabricScript = file("build.fabric.gradle.kts").readText()
    val plugin = Regex("""alias\(libs\.plugins\.fabric\.loom\)(\r?\n)""")
    check(plugin.containsMatchIn(fabricScript)) { "build.fabric.gradle.kts no longer applies libs.plugins.fabric.loom" }
    val remapScript = "// GENERATED by settings.gradle.kts from build.fabric.gradle.kts - edit that file instead.\n" +
        fabricScript.replaceFirst(plugin, "alias(libs.plugins.fabric.loom.remap)$1")
    val out = file("build.fabric-remap.gradle.kts")
    if (!out.exists() || out.readText() != remapScript) out.writeText(remapScript)
}

// One build per Minecraft version and loader: project versions/<mc>-<loader>, built by build.<loader>.gradle.kts
// from the shared src/ (version- and loader-specific code sits in //? if ... comments, see stonecutter.gradle.kts).
stonecutter {
    create(rootProject) {
        fun match(version: String, vararg loaders: String) {
            for (loader in loaders) version("$version-$loader", version).buildscript("build.$loader.gradle.kts")
        }
        version("1.21.11-fabric", "1.21.11").buildscript("build.fabric-remap.gradle.kts")
        match("26.1.2", "fabric")
        match("26.2", "fabric", "neoforge", "forge")
        match("26.3", "fabric", "neoforge", "forge")
        // The version the committed sources are written for (its //? blocks are the uncommented ones).
        vcsVersion = "26.2-fabric"
    }
}

